// Helper to generate initial ticket layout with tier pricing and random sample booked seats
export const generateSeatMap = (theatre) => {
  const tickets = {};
  const tiers = [
    { name: "Balcony", prefix: "B", rows: theatre.balconySeats?.rows || 2, cols: theatre.balconySeats?.cols || 10, price: theatre.balconySeatPrice || 350 },
    { name: "Middle", prefix: "M", rows: theatre.middleSeats?.rows || 3, cols: theatre.middleSeats?.cols || 10, price: theatre.middleSeatPrice || 250 },
    { name: "Lower", prefix: "L", rows: theatre.lowerSeats?.rows || 2, cols: theatre.lowerSeats?.cols || 150, price: theatre.lowerSeatPrice || 150 },
  ];

  tiers.forEach((tier) => {
    for (let r = 1; r <= tier.rows; r++) {
      const rowLetter = String.fromCharCode(64 + r); // A, B, C...
      for (let c = 1; c <= tier.cols; c++) {
        const seatId = `${tier.prefix}${rowLetter}${c}`;
        // Give 10% chance of pre-booked seat for realistic realism
        const isBooked = Math.random() < 0.12;
        tickets[seatId] = {
          seatNumber: seatId,
          tier: tier.name,
          price: tier.price,
          status: isBooked ? 'booked' : 'available',
          lockedBy: null,
          lockedUntil: null,
        };
      }
    }
  });

  return tickets;
};
